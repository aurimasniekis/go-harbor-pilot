var updateUIRules = flag.Bool("update", false, "rewrite web/src/features/config/reasoningRules.gen.ts")

// uiRulesPath is the web UI's copy of the reasoning option's rules.
var uiRulesPath = filepath.Join("..", "..", "web", "src", "features", "config", "reasoningRules.gen.ts")

// uiReasoningRules is what the model dialog needs to offer only what
// validateModelReasoning accepts.
func uiReasoningRules() map[string]any {
	styleProtocol := map[string]string{}
	styleLevels := map[string][]string{}
	defaultHistory := map[string]string{}
	for _, n := range reasoning.Names() {
		m, _ := reasoning.Lookup(n)
		styleProtocol[n] = string(m.Protocol())
		styleLevels[n] = append([]string{}, m.DefaultEfforts()...)
		defaultHistory[n] = m.DefaultHistoryField()
	}
	typeProtocols := map[string][]string{}
	protocolDefault := map[string]string{}
	for typ := range reasoningStyles {
		for _, p := range chatProtocolsFor(typ) {
			typeProtocols[typ] = append(typeProtocols[typ], string(p))
			protocolDefault[string(p)] = reasoning.DefaultFor(p).Name()
		}
	}
	budgetTypes := []string{}
	for typ := range budgetProtocols {
		budgetTypes = append(budgetTypes, typ)
	}
	slices.Sort(budgetTypes)
	return map[string]any{
		"ladder":                reasoning.Ladder[1:],
		"stylesByType":          reasoningStyles,
		"styleProtocol":         styleProtocol,
		"styleLevels":           styleLevels,
		"defaultHistoryField":   defaultHistory,
		"typeProtocols":         typeProtocols,
		"protocolDefaultStyle":  protocolDefault,
		"budgetTypes":           budgetTypes,
		"levelOnlyStyles":       effortOnlyStyles,
		"historyTypes":          []string{ProviderOpenAICompatible, ProviderOllama},
		"reservedHistoryFields": reservedMessageFields,
		"historyFieldPattern":   historyFieldRE.String(),
		"chatProtocol":          string(ir.OpenAIChat),
	}
}

// TestUIReasoningRules keeps the web UI's rule tables equal to the server's
// validation: regenerate with `go test ./internal/controlplane -run
// TestUIReasoningRules -update`.
func TestUIReasoningRules(t *testing.T) {
	raw, err := json.MarshalIndent(uiReasoningRules(), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Generated by internal/controlplane TestUIReasoningRules (-update); do not edit.\n")
	b.WriteString("// The reasoning option's rules as the server validates them (reasoning_spec.go).\n")
	b.WriteString("export const reasoningRules = ")
	b.Write(raw)
	b.WriteString(" as const\n")
	if *updateUIRules {
		if err := os.WriteFile(uiRulesPath, b.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(uiRulesPath)
	if err != nil {
		t.Fatalf("read %s (run with -update): %v", uiRulesPath, err)
	}
	if !bytes.Equal(got, b.Bytes()) {
		t.Errorf("%s is out of date: run go test ./internal/controlplane -run TestUIReasoningRules -update", uiRulesPath)
	}
}
